'use strict';
// Test de bout en bout dans un vrai navigateur (Playwright/Chromium).
// Usage : node tests/site.e2e.js   (lance lui-même deux serveurs locaux, Resend simulé)
const { spawn } = require('node:child_process');
const path = require('node:path');
const assert = require('node:assert');
const { chromium } = require('playwright');

const PAGES = ['/', '/en/', '/mentions-legales.html', '/cgu.html', '/confidentialite.html', '/cookies.html',
  '/en/legal-notice.html', '/en/terms.html', '/en/privacy.html', '/en/cookies.html'];

function start(port, env) {
  const p = spawn(process.execPath, [path.join(__dirname, 'local-server.js'), String(port)], {
    env: Object.assign({}, process.env, env), stdio: ['ignore', 'pipe', 'inherit']
  });
  return new Promise((ok) => p.stdout.once('data', () => ok(p)));
}

async function fill(page) {
  await page.fill('#f-first', 'Test');
  await page.fill('#f-last', 'Visiteur');
  await page.fill('#f-email', 'test@example.com');
  await page.fill('#f-msg', 'Message de test pour vérifier le formulaire.');
  await page.check('input[name="consent"]');
  await page.waitForTimeout(3200); // délai anti-robot
}

(async () => {
  const okSrv = await start(4101, { MOCK_RESEND: 'ok', RESEND_API_KEY: 'test' });
  const failSrv = await start(4102, { MOCK_RESEND: 'fail', RESEND_API_KEY: 'test' });
  const browser = await chromium.launch();
  let failures = 0;
  const check = async (name, fn) => {
    try { await fn(); console.log('ok   ' + name); } catch (e) { failures++; console.log('FAIL ' + name + '\n     ' + e.message); }
  };
  try {
    const ctx = await browser.newContext();
    const page = await ctx.newPage();
    const external = [];
    page.on('request', (r) => { const u = new URL(r.url()); if (u.hostname !== 'localhost') external.push(r.url()); });

    for (const p of PAGES) {
      await check('page ' + p + ' : chargement, liens internes, aucun appel externe', async () => {
        const errors = [];
        page.removeAllListeners('pageerror');
        page.on('pageerror', (e) => errors.push(e.message));
        external.length = 0;
        const r = await page.goto('http://localhost:4101' + p, { waitUntil: 'networkidle' });
        assert.strictEqual(r.status(), 200);
        assert.deepStrictEqual(errors, []);
        assert.deepStrictEqual(external, [], 'requêtes externes : ' + external.join(', '));
        const cookies = await ctx.cookies();
        assert.strictEqual(cookies.length, 0, 'aucun cookie attendu');
        const hrefs = await page.$$eval('a[href^="/"]', (as) => as.map((a) => a.getAttribute('href').split('#')[0]));
        for (const h of new Set(hrefs)) {
          const rr = await page.request.get('http://localhost:4101' + h);
          assert.strictEqual(rr.status(), 200, 'lien cassé : ' + h);
        }
        const fontOk = await page.evaluate(() => document.fonts.check('16px Montserrat') && document.fonts.check('16px Inter'));
        assert.ok(fontOk, 'polices auto-hébergées non chargées');
        const text = (await page.textContent('body')).toLowerCase();
        assert.ok(!/\bholding num[ée]rique camerounaise\b/.test(text), '« holding » présenté comme un fait');
        assert.ok(!/claude|anthropic|chatgpt|openai|généré par|generated by/.test(text), "trace d'outil de génération");
      });
    }

    await check('mobile (375 px) : pas de défilement horizontal', async () => {
      const m = await browser.newPage({ viewport: { width: 375, height: 800 } });
      for (const p of ['/', '/en/', '/confidentialite.html']) {
        await m.goto('http://localhost:4101' + p);
        const w = await m.evaluate(() => document.documentElement.scrollWidth);
        assert.ok(w <= 375, p + ' largeur ' + w);
      }
      await m.close();
    });

    await check('formulaire FR : confirmation affichée UNIQUEMENT après envoi réussi', async () => {
      await page.goto('http://localhost:4101/#contact');
      await page.click('button[type="submit"]');
      assert.match(await page.textContent('#f-status'), /remplir tous les champs/);
      await fill(page);
      const [resp] = await Promise.all([page.waitForResponse('**/api/contact'), page.click('button[type="submit"]')]);
      assert.strictEqual(resp.status(), 200);
      await page.waitForSelector('#f-status.ok');
      assert.match(await page.textContent('#f-status'), /bien été envoyé/);
      assert.strictEqual(await page.inputValue('#f-first'), '', 'formulaire vidé après succès');
    });

    await check('formulaire EN : confirmation en anglais', async () => {
      await page.goto('http://localhost:4101/en/#contact');
      await fill(page);
      await page.click('button[type="submit"]');
      await page.waitForSelector('#f-status.ok');
      assert.match(await page.textContent('#f-status'), /has been sent/);
    });

    await check("formulaire : échec d'envoi -> message d'erreur, données conservées, pas de confirmation", async () => {
      await page.goto('http://localhost:4102/#contact');
      await fill(page);
      await page.click('button[type="submit"]');
      await page.waitForSelector('#f-status.err');
      const t = await page.textContent('#f-status');
      assert.match(t, /n'a pas pu être envoyé/);
      assert.doesNotMatch(t, /bien été envoyé/);
      assert.strictEqual(await page.inputValue('#f-first'), 'Test');
    });

    await check('formulaire : serveur injoignable -> erreur', async () => {
      await page.goto('http://localhost:4101/#contact');
      await page.route('**/api/contact', (r) => r.abort());
      await fill(page);
      await page.click('button[type="submit"]');
      await page.waitForSelector('#f-status.err');
      await page.unroute('**/api/contact');
    });
  } finally {
    await browser.close();
    okSrv.kill();
    failSrv.kill();
  }
  console.log(failures ? failures + ' échec(s)' : 'Tous les tests sont passés');
  process.exit(failures ? 1 : 0);
})();
